import 'dart:convert';
import 'dart:io';

import 'matrix_model.dart';

/// Formatter for exporting [AccessMatrixReport] in Markdown, Console ASCII, and JSON formats.
class MatrixFormatter {
  const MatrixFormatter();

  /// Formats the report into GitHub-flavored Markdown.
  String formatMarkdown(AccessMatrixReport report) {
    final buffer = StringBuffer();
    final sortedRoles = report.allRoles.toList()..sort();
    final sortedPermissions = report.allPermissions.toList()..sort();

    buffer.writeln('# 🛡️ Access Control Matrix (ACM) Report');
    buffer.writeln();
    buffer.writeln('> Automatically generated by **Guardify CLI** on `${report.generatedAt.toIso8601String()}`.');
    buffer.writeln();

    // Summary Statistics
    buffer.writeln('## 📊 Summary Overview');
    buffer.writeln();
    buffer.writeln('| Metric | Count |');
    buffer.writeln('|---|---|');
    buffer.writeln('| **Total Protected Components** | `${report.components.length}` |');
    buffer.writeln('| **Configured Roles** | `${sortedRoles.length}` (${sortedRoles.join(', ')}) |');
    buffer.writeln('| **Fine-Grained Permissions** | `${sortedPermissions.length}` |');
    buffer.writeln();

    if (report.components.isEmpty) {
      buffer.writeln('*No `@Secured` or `RoleGate` components found in the specified path.*');
      return buffer.toString();
    }

    // Role Access Matrix
    buffer.writeln('## 🔐 Role Access Matrix');
    buffer.writeln();

    final roleHeaders = sortedRoles.map((r) => '`$r`').join(' | ');
    final separator = List.filled(sortedRoles.length, '---').join(' | ');

    buffer.writeln('| Component | Source Location | Fallback | $roleHeaders |');
    buffer.writeln('|---|---|---| $separator |');

    for (final comp in report.components) {
      final loc = '`${comp.filePath}:${comp.lineNumber}`';
      final roleCells = sortedRoles.map((role) {
        final status = comp.evaluateRole(role);
        return switch (status) {
          AccessStatus.granted => '✅ Allowed',
          AccessStatus.disabled => '🔒 Disabled',
          AccessStatus.denied => '❌ Denied',
        };
      }).join(' | ');

      buffer.writeln('| **`${comp.name}`** | $loc | `${comp.fallbackType}` | $roleCells |');
    }

    buffer.writeln();

    // Permission Details Table
    if (sortedPermissions.isNotEmpty) {
      buffer.writeln('## 🔑 Permission-Based Access Details (PBAC)');
      buffer.writeln();
      buffer.writeln('| Component | Required Permissions | Match Logic |');
      buffer.writeln('|---|---|---|');
      for (final comp in report.components) {
        if (comp.allowedPermissions.isNotEmpty) {
          final perms = comp.allowedPermissions.map((p) => '`$p`').join(', ');
          final logic = comp.requireAll ? '**AND (All)**' : '**OR (Any)**';
          buffer.writeln('| **`${comp.name}`** | $perms | $logic |');
        }
      }
      buffer.writeln();
    }

    return buffer.toString();
  }

  /// Formats the report into an ANSI-compatible or plain ASCII Console output.
  String formatConsole(AccessMatrixReport report, {bool? useAnsi}) {
    final buffer = StringBuffer();
    final sortedRoles = report.allRoles.toList()..sort();
    final isAnsi = useAnsi ??
        (stdout.hasTerminal &&
            stdout.supportsAnsiEscapes &&
            !Platform.environment.containsKey('NO_COLOR'));

    final green = isAnsi ? '\x1B[32m' : '';
    final red = isAnsi ? '\x1B[31m' : '';
    final yellow = isAnsi ? '\x1B[33m' : '';
    final cyan = isAnsi ? '\x1B[36m' : '';
    final bold = isAnsi ? '\x1B[1m' : '';
    final reset = isAnsi ? '\x1B[0m' : '';

    buffer.writeln('$bold$cyan════════════════════════════════════════════════════════════════════════$reset');
    buffer.writeln('$bold$cyan   🛡️  GUARDIFY ACCESS CONTROL MATRIX (ACM) REPORT$reset');
    buffer.writeln('$bold$cyan════════════════════════════════════════════════════════════════════════$reset');
    buffer.writeln('Total Components: ${report.components.length} | Roles: [${sortedRoles.join(', ')}]');
    buffer.writeln('------------------------------------------------------------------------');

    if (report.components.isEmpty) {
      buffer.writeln('No role-gated components found.');
      return buffer.toString();
    }

    for (final comp in report.components) {
      buffer.writeln('$bold• ${comp.name}$reset ($cyan${comp.filePath}:${comp.lineNumber}$reset) [Fallback: ${comp.fallbackType}]');
      if (comp.allowedPermissions.isNotEmpty) {
        buffer.writeln('  Permissions: ${comp.allowedPermissions.join(', ')} (requireAll: ${comp.requireAll})');
      }

      final roleStatuses = sortedRoles.map((role) {
        final status = comp.evaluateRole(role);
        return switch (status) {
          AccessStatus.granted => '$green[✅ $role]$reset',
          AccessStatus.disabled => '$yellow[🔒 $role]$reset',
          AccessStatus.denied => '$red[❌ $role]$reset',
        };
      }).join(' ');

      buffer.writeln('  Roles: $roleStatuses');
      buffer.writeln();
    }

    buffer.writeln('$bold$cyan────────────────────────────────────────────────────────────────────────$reset');
    buffer.writeln('Legend: $green✅ Allowed$reset  $yellow🔒 Disabled Overlay$reset  $red❌ Access Denied$reset');
    return buffer.toString();
  }

  /// Formats the report into formatted JSON string.
  String formatJson(AccessMatrixReport report) {
    const encoder = JsonEncoder.withIndent('  ');
    return encoder.convert(report.toJson());
  }
}
